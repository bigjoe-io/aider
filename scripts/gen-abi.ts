/**
 * Generates src/aider/abi.ts from the Foundry build artifact.
 *   bun run abi:gen   (run `forge build` first if contracts/out is missing)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const artifactPath = join(root, 'contracts/out/Aider.sol/Aider.json')
const outPath = join(root, 'src/aider/abi.ts')

interface Artifact {
  abi: Array<{ type: string; name?: string }>
}

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8')) as Artifact
const abi = artifact.abi.filter((e) => e.type === 'function' || e.type === 'event' || e.type === 'error')
const count = (t: string) => abi.filter((e) => e.type === t).length

const ERC20_ABI = [
  { type: 'function', name: 'balanceOf', stateMutability: 'view', inputs: [{ name: 'account', type: 'address' }], outputs: [{ name: '', type: 'uint256' }] },
  { type: 'function', name: 'allowance', stateMutability: 'view', inputs: [{ name: 'owner', type: 'address' }, { name: 'spender', type: 'address' }], outputs: [{ name: '', type: 'uint256' }] },
  { type: 'function', name: 'approve', stateMutability: 'nonpayable', inputs: [{ name: 'spender', type: 'address' }, { name: 'amount', type: 'uint256' }], outputs: [{ name: '', type: 'bool' }] },
  { type: 'function', name: 'decimals', stateMutability: 'view', inputs: [], outputs: [{ name: '', type: 'uint8' }] },
  { type: 'function', name: 'symbol', stateMutability: 'view', inputs: [], outputs: [{ name: '', type: 'string' }] },
  { type: 'event', name: 'Transfer', anonymous: false, inputs: [{ name: 'from', type: 'address', indexed: true }, { name: 'to', type: 'address', indexed: true }, { name: 'value', type: 'uint256', indexed: false }] },
  { type: 'event', name: 'Approval', anonymous: false, inputs: [{ name: 'owner', type: 'address', indexed: true }, { name: 'spender', type: 'address', indexed: true }, { name: 'value', type: 'uint256', indexed: false }] },
]

const header = `/*
 * Aider contract ABI. GENERATED by scripts/gen-abi.ts from contracts/out/Aider.sol/Aider.json.
 * Do not edit by hand: run \`bun run abi:gen\` after changing contracts/Aider.sol.
 * ${count('function')} functions, ${count('event')} events, ${count('error')} errors.
 */
`

const body = `${header}
export const AIDER_ABI = ${JSON.stringify(abi, null, 2)} as const

/** Minimal ERC-20 ABI for USDC (6 decimals). */
export const ERC20_ABI = ${JSON.stringify(ERC20_ABI, null, 2)} as const

export type AiderAbi = typeof AIDER_ABI
`

writeFileSync(outPath, body)
console.log(`wrote ${outPath} (${abi.length} entries)`)
