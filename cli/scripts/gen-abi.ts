// Regenerates src/abi.ts (the full Aider ABI: functions, events and errors) from the Foundry
// artifact. Run `forge build` at the repo root first, then `bun run abi:gen` from cli/
// (or `bun scripts/gen-abi.ts path/to/Aider.json`).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

type Json = string | number | boolean | null | Json[] | { [key: string]: Json };

const cliDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = resolve(process.argv[2] ?? join(cliDir, "..", "contracts", "out", "Aider.sol", "Aider.json"));
const out = join(cliDir, "src", "abi.ts");

const parsed = JSON.parse(readFileSync(artifact, "utf8")) as { abi?: Json };
const abi = parsed.abi;
if (!Array.isArray(abi) || abi.length === 0) {
  console.error(`No ABI found in ${artifact}`);
  process.exit(1);
}

// internalType only names Solidity types (e.g. "struct Aider.PaymentRequest"); encoding ignores it.
function strip(value: Json): Json {
  if (Array.isArray(value)) return value.map(strip);
  if (value !== null && typeof value === "object") {
    const res: { [key: string]: Json } = {};
    for (const [key, v] of Object.entries(value)) if (key !== "internalType") res[key] = strip(v);
    return res;
  }
  return value;
}

const list: Json[] = abi;
const entries: Json[] = list.map(strip);
const count = (type: string): number =>
  entries.filter((e) => e !== null && typeof e === "object" && !Array.isArray(e) && e.type === type).length;

const source = `// GENERATED by scripts/gen-abi.ts from contracts/out/Aider.sol/Aider.json — do not edit by hand.
// Full ABI of the Aider contract (v2): ${count("function")} functions, ${count("event")} events, ${count("error")} errors.
// Every v1 ("Leash") entry is unchanged, so this ABI also works against the deployed v1 contract;
// calls to v2-only functions revert there and the CLI falls back.
export const AIDER_ABI = ${JSON.stringify(entries, null, 2)} as const;
`;

writeFileSync(out, source);
console.log(`Wrote ${out} (${entries.length} entries)`);
